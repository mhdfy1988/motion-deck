const {contextBridge,ipcRenderer}=require('electron');
// 只暴露固定业务操作，绝不暴露ipcRenderer、Node或任意文件路径读写。
contextBridge.exposeInMainWorld('motionDeckDesktop',Object.freeze({
 windowState:()=>ipcRenderer.invoke('motiondeck:window','state'),
 minimizeWindow:()=>ipcRenderer.invoke('motiondeck:window','minimize'),
 toggleMaximizeWindow:()=>ipcRenderer.invoke('motiondeck:window','maximize'),
 closeWindow:()=>ipcRenderer.invoke('motiondeck:window','close'),
 onWindowState:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('motiondeck:window-state',listener);return ()=>ipcRenderer.removeListener('motiondeck:window-state',listener);},
 controlState:()=>ipcRenderer.invoke('motiondeck:control','state'),
 onAssistantState:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('motiondeck:assistant-state',listener);return ()=>ipcRenderer.removeListener('motiondeck:assistant-state',listener);},
 setControlEnabled:enabled=>ipcRenderer.invoke('motiondeck:control','enable',enabled),
 setControlWrite:enabled=>ipcRenderer.invoke('motiondeck:control','write',enabled),
 setControlTimeline:enabled=>ipcRenderer.invoke('motiondeck:control','timeline',enabled),
 saveControlExport:bytes=>ipcRenderer.invoke('motiondeck:control-export',bytes),
 controlDraftState:dirty=>ipcRenderer.invoke('motiondeck:control','draft',dirty),
 saveControlCapture:bytes=>ipcRenderer.invoke('motiondeck:control-capture',bytes),
 saveControlManifest:value=>ipcRenderer.invoke('motiondeck:control-manifest',value),
 saveControlVideo:value=>ipcRenderer.invoke('motiondeck:control-video',value),
 controlReady:()=>ipcRenderer.invoke('motiondeck:control','ready'),
 answerControlQuery:value=>ipcRenderer.invoke('motiondeck:control-reply',value),
 onControlQuery:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('motiondeck:control-query',listener);return ()=>ipcRenderer.removeListener('motiondeck:control-query',listener);},
 getRecord:id=>ipcRenderer.invoke('motiondeck:data','get',id),
 putRecords:payload=>ipcRenderer.invoke('motiondeck:data','put',payload),
 migrationInfo:()=>ipcRenderer.invoke('motiondeck:data','info'),
 migrateRecords:records=>ipcRenderer.invoke('motiondeck:data','migrate',{records}),
 settings:()=>ipcRenderer.invoke('motiondeck:settings','info'),
 chooseDirectory:kind=>ipcRenderer.invoke('motiondeck:settings','choose',kind),
 openDirectory:kind=>ipcRenderer.invoke('motiondeck:settings','open',kind),
 backup:()=>ipcRenderer.invoke('motiondeck:settings','backup'),
 restore:()=>ipcRenderer.invoke('motiondeck:settings','restore'),
 clearCache:()=>ipcRenderer.invoke('motiondeck:settings','clearCache'),
 updateState:()=>ipcRenderer.invoke('motiondeck:update','state'),
 checkUpdate:()=>ipcRenderer.invoke('motiondeck:update','check'),
 downloadUpdate:()=>ipcRenderer.invoke('motiondeck:update','download'),
 cancelUpdate:()=>ipcRenderer.invoke('motiondeck:update','cancel'),
 installUpdate:confirmed=>ipcRenderer.invoke('motiondeck:update','install',confirmed),
 openReleases:()=>ipcRenderer.invoke('motiondeck:update','releases'),
 onUpdate:callback=>{const listener=(_event,state)=>callback(state);ipcRenderer.on('motiondeck:update-state',listener);return ()=>ipcRenderer.removeListener('motiondeck:update-state',listener);}
}));
